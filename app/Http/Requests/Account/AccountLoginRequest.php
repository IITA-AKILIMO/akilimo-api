namespace App\Http\Requests\Account;

class AccountLoginRequest extends AccountRequest
{
    public function rules(): array
    {
        return [
            'email' => ['required', 'email', 'max:255'],
            'password' => ['required', 'string'],
            'device_token' => ['nullable', 'string', 'max:255'],
        ];
    }
}
